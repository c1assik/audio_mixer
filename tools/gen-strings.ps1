# Генерирует классы строк (Strings, CoreStrings, AudioStrings) из нейтральных .resx.
# Класс лежит в репозитории, а не создаётся сборкой: временный проект WPF (wpftmp) не видит
# сгенерированный сборкой код, и {x:Static res:Strings.…} в XAML не компилируется.
# Запуск после правки .resx: powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen-strings.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

$targets = @(
    @{ Resx = 'src\Mixer.App\Resources\Strings.resx'; Namespace = 'Mixer.App.Resources'; Class = 'Strings' },
    @{ Resx = 'src\Mixer.Core\Resources\CoreStrings.resx'; Namespace = 'Mixer.Core.Resources'; Class = 'CoreStrings' },
    @{ Resx = 'src\Mixer.Audio\Resources\AudioStrings.resx'; Namespace = 'Mixer.Audio.Resources'; Class = 'AudioStrings' }
)

foreach ($t in $targets) {
    $path = Join-Path $root $t.Resx
    [xml]$xml = Get-Content -LiteralPath $path -Encoding UTF8 -Raw
    $cls = $t.Class
    $ns = $t.Namespace
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('// <auto-generated>')
    [void]$sb.AppendLine("// tools/gen-strings.ps1 from $cls.resx. Do not edit by hand: change the .resx files and run the script again.")
    [void]$sb.AppendLine('// </auto-generated>')
    [void]$sb.AppendLine('#nullable enable')
    [void]$sb.AppendLine('using System.Globalization;')
    [void]$sb.AppendLine('using System.Resources;')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("namespace $ns;")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("public static class $cls")
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine("    public static ResourceManager ResourceManager { get; } = new(""$ns.$cls"", typeof($cls).Assembly);")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    /// <summary>Culture to look strings up in; null follows CurrentUICulture.</summary>')
    [void]$sb.AppendLine('    public static CultureInfo? Culture { get; set; }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    private static string Get(string name) => ResourceManager.GetString(name, Culture) ?? name;')
    foreach ($d in $xml.root.data) {
        $name = $d.name
        $summary = [System.Security.SecurityElement]::Escape(($d.value -replace '\s+', ' '))
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine("    /// <summary>$summary</summary>")
        [void]$sb.AppendLine("    public static string $name => Get(""$name"");")
    }
    [void]$sb.AppendLine('}')
    $out = [System.IO.Path]::ChangeExtension($path, '.Designer.cs')
    [System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($true)))
    Write-Host "$out"
}
